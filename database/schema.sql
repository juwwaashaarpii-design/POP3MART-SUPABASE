create extension if not exists pgcrypto;

-- 1. Profil akun: setiap pendaftaran Auth otomatis dibuat sebagai buyer.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique,
  full_name text not null default '',
  phone text not null default '',
  address text not null default '',
  role text not null default 'buyer' check (role in ('buyer', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    'buyer'
  )
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Fungsi ini dipakai policy RLS untuk mengecek role tanpa recursion policy profiles.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to anon, authenticated;

-- 2. Produk / figures.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Collectible',
  description text not null default '',
  price numeric(14,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  image_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_active_created_idx
  on public.products (is_active, created_at desc);

-- 3. Wishlist buyer.
create table if not exists public.wishlist_items (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint wishlist_user_product_unique unique (user_id, product_id)
);

create index if not exists wishlist_user_idx on public.wishlist_items(user_id);

-- 4. Pengaturan toko (satu baris dengan id = 1).
create table if not exists public.store_settings (
  id smallint primary key default 1 check (id = 1),
  store_name text not null default 'POP-3 MART',
  support_email text not null default '',
  whatsapp text not null default '',
  announcement text not null default '',
  updated_at timestamptz not null default now()
);

insert into public.store_settings (id, store_name)
values (1, 'POP-3 MART')
on conflict (id) do nothing;

-- 5. Aktifkan Row Level Security (RLS) untuk seluruh tabel publik.
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.wishlist_items enable row level security;
alter table public.store_settings enable row level security;

-- Bersihkan policy bernama sama agar script bisa dijalankan ulang.
drop policy if exists "Profile owner or admin can read profiles" on public.profiles;
drop policy if exists "Buyer can update own profile" on public.profiles;
drop policy if exists "Admin can update profiles" on public.profiles;
create policy "Profile owner or admin can read profiles"
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());
create policy "Buyer can update own profile"
on public.profiles for update to authenticated
using (id = auth.uid())
with check (id = auth.uid() and role = 'buyer');
create policy "Admin can update profiles"
on public.profiles for update to authenticated
using (public.is_admin())
with check (public.is_admin());

-- Produk aktif bisa dibaca publik. Hanya admin dapat melihat semua dan mengubah katalog.
drop policy if exists "Anyone can read active products" on public.products;
drop policy if exists "Admins can manage products" on public.products;
create policy "Anyone can read active products"
on public.products for select to anon, authenticated
using (is_active = true);
create policy "Admins can manage products"
on public.products for all to authenticated
using (public.is_admin())
with check (public.is_admin());

-- Wishlist hanya dapat dibaca/ditambah/dihapus oleh pemiliknya.
drop policy if exists "Buyer reads own wishlist" on public.wishlist_items;
drop policy if exists "Buyer adds to own wishlist" on public.wishlist_items;
drop policy if exists "Buyer removes own wishlist" on public.wishlist_items;
create policy "Buyer reads own wishlist"
on public.wishlist_items for select to authenticated
using (user_id = auth.uid() or public.is_admin());
create policy "Buyer adds to own wishlist"
on public.wishlist_items for insert to authenticated
with check (user_id = auth.uid());
create policy "Buyer removes own wishlist"
on public.wishlist_items for delete to authenticated
using (user_id = auth.uid() or public.is_admin());

-- Pengaturan toko boleh dibaca publik, tetapi hanya admin yang dapat mengubahnya.
drop policy if exists "Anyone can read store settings" on public.store_settings;
drop policy if exists "Admins manage store settings" on public.store_settings;
create policy "Anyone can read store settings"
on public.store_settings for select to anon, authenticated
using (true);
create policy "Admins manage store settings"
on public.store_settings for all to authenticated
using (public.is_admin())
with check (public.is_admin());

-- Berikan hak operasi SQL yang dibutuhkan. RLS tetap menjadi penjaga akses per baris.
grant usage on schema public to anon, authenticated;
grant select on public.products, public.store_settings to anon, authenticated;
grant select, update on public.profiles to authenticated;
grant select, insert, delete on public.wishlist_items to authenticated;
grant insert, update, delete on public.products to authenticated;
grant insert, update, delete on public.store_settings to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- 6. Supabase Storage untuk gambar produk.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'product-images',
  'product-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- File gambar dapat ditampilkan publik, tetapi upload/ubah/hapus hanya oleh admin.
drop policy if exists "Public can view product images" on storage.objects;
drop policy if exists "Admins upload product images" on storage.objects;
drop policy if exists "Admins update product images" on storage.objects;
drop policy if exists "Admins delete product images" on storage.objects;
create policy "Public can view product images"
on storage.objects for select to anon, authenticated
using (bucket_id = 'product-images');
create policy "Admins upload product images"
on storage.objects for insert to authenticated
with check (bucket_id = 'product-images' and public.is_admin());
create policy "Admins update product images"
on storage.objects for update to authenticated
using (bucket_id = 'product-images' and public.is_admin())
with check (bucket_id = 'product-images' and public.is_admin());
create policy "Admins delete product images"
on storage.objects for delete to authenticated
using (bucket_id = 'product-images' and public.is_admin());

