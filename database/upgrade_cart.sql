-- POP-3 MART | KERANJANG + CHECKOUT MULTI PRODUK
-- Jalankan sebagai NEW QUERY, setelah schema.sql dan upgrade_checkout.sql sebelumnya.
-- Tidak menghapus tabel, akun, produk, atau pesanan yang sudah ada.

CREATE TABLE IF NOT EXISTS public.cart_items (
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  quantity integer NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 20),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, product_id)
);
CREATE INDEX IF NOT EXISTS cart_items_product_idx ON public.cart_items(product_id);
ALTER TABLE public.cart_items ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Cart buyer owns rows" ON public.cart_items;
CREATE POLICY "Cart buyer owns rows" ON public.cart_items FOR ALL TO authenticated
  USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()));
REVOKE ALL ON public.cart_items FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cart_items TO authenticated;

-- Snapshot detail tiap figure dalam 1 pesanan keranjang. Baris legacy tetap valid.
CREATE TABLE IF NOT EXISTS public.order_line_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL,
  product_image_url text,
  unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 20),
  line_total numeric(14,2) NOT NULL CHECK (line_total >= 0)
);
CREATE INDEX IF NOT EXISTS order_line_items_order_idx ON public.order_line_items(order_id);
ALTER TABLE public.order_line_items ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Owner or admin view order lines" ON public.order_line_items;
CREATE POLICY "Owner or admin view order lines" ON public.order_line_items FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.orders o
    WHERE o.id = order_id AND (o.user_id = (SELECT auth.uid()) OR public.is_admin())
  ));
REVOKE ALL ON public.order_line_items FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.order_line_items TO authenticated;

-- Checkout cart atomik: harga dibaca dari DB, produk dikunci, stok berkurang sekali,
-- satu ongkir untuk seluruh keranjang, lalu isi cart dihapus jika transaksi sukses.
CREATE OR REPLACE FUNCTION public.place_cart_order(
  p_payment_method_id bigint, p_shipping_address text
) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_cart public.cart_items%ROWTYPE;
  v_product public.products%ROWTYPE;
  v_method public.payment_methods%ROWTYPE;
  v_fee numeric(14,2) := 0;
  v_subtotal numeric(14,2) := 0;
  v_address text := trim(coalesce(p_shipping_address,''));
  v_count integer := 0;
  v_qty integer := 0;
  v_first_name text;
  v_first_image text;
  v_first_price numeric(14,2);
  v_order_id uuid;
BEGIN
  IF v_uid IS NULL OR NOT EXISTS (SELECT 1 FROM public.profiles WHERE id=v_uid AND role='buyer') THEN
    RAISE EXCEPTION 'Login sebagai Buyer terlebih dahulu.';
  END IF;
  IF char_length(v_address) < 10 OR char_length(v_address) > 1000 THEN
    RAISE EXCEPTION 'Alamat pengiriman harus 10-1000 karakter.';
  END IF;
  SELECT * INTO v_method FROM public.payment_methods WHERE id=p_payment_method_id AND is_active;
  IF NOT FOUND THEN RAISE EXCEPTION 'Metode pembayaran tidak tersedia.'; END IF;
  IF (v_method.kind='bank' AND (v_method.account_number='' OR v_method.account_name=''))
     OR (v_method.kind='qris' AND v_method.qris_image_url='') THEN
    RAISE EXCEPTION 'Metode pembayaran belum dikonfigurasi lengkap.';
  END IF;

  -- LOCK setiap baris keranjang dan produk; bila transaksi gagal semua otomatis rollback.
  FOR v_cart IN
    SELECT * FROM public.cart_items WHERE user_id=v_uid ORDER BY product_id FOR UPDATE
  LOOP
    SELECT * INTO v_product FROM public.products WHERE id=v_cart.product_id FOR UPDATE;
    IF NOT FOUND OR NOT v_product.is_active THEN
      RAISE EXCEPTION 'Ada figure yang tidak tersedia lagi. Periksa keranjang.';
    END IF;
    IF v_product.stock < v_cart.quantity THEN
      RAISE EXCEPTION 'Stok % tidak cukup. Tersedia: %.', v_product.name, v_product.stock;
    END IF;
    v_count := v_count + 1;
    v_qty := v_qty + v_cart.quantity;
    IF v_qty > 20 THEN RAISE EXCEPTION 'Maksimal total 20 figure per pesanan.'; END IF;
    v_subtotal := v_subtotal + (v_product.price * v_cart.quantity);
    IF v_count=1 THEN
      v_first_name := v_product.name;
      v_first_image := v_product.image_url;
      v_first_price := v_product.price;
    END IF;
    UPDATE public.products SET stock=stock-v_cart.quantity, updated_at=now() WHERE id=v_product.id;
  END LOOP;
  IF v_count=0 THEN RAISE EXCEPTION 'Keranjang belanja masih kosong.'; END IF;

  SELECT COALESCE(shipping_fee,0) INTO v_fee FROM public.store_settings WHERE id=1;
  v_fee := COALESCE(v_fee,0);
  INSERT INTO public.orders (
    user_id, product_id, product_name, product_image_url, unit_price, quantity,
    subtotal, shipping_fee, total_amount, shipping_address,
    payment_method_id, payment_method_snapshot
  ) VALUES (
    v_uid, NULL,
    CASE WHEN v_count=1 THEN v_first_name ELSE v_first_name || ' + ' || (v_count-1)::text || ' figure lainnya' END,
    v_first_image, v_first_price, v_qty,
    v_subtotal, v_fee, v_subtotal+v_fee, v_address,
    p_payment_method_id,
    jsonb_build_object(
      'name',v_method.name,'kind',v_method.kind,'provider',v_method.provider,
      'account_name',v_method.account_name,'account_number',v_method.account_number,
      'qris_image_url',v_method.qris_image_url,'instructions',v_method.instructions
    )
  ) RETURNING id INTO v_order_id;

  INSERT INTO public.order_line_items (
    order_id,product_id,product_name,product_image_url,unit_price,quantity,line_total
  )
  SELECT v_order_id,p.id,p.name,p.image_url,p.price,ci.quantity,p.price*ci.quantity
  FROM public.cart_items ci
  JOIN public.products p ON p.id=ci.product_id
  WHERE ci.user_id=v_uid;
  DELETE FROM public.cart_items WHERE user_id=v_uid;
  RETURN v_order_id;
END; $$;
REVOKE ALL ON FUNCTION public.place_cart_order(bigint,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.place_cart_order(bigint,text) TO authenticated;

-- Pembatalan pesanan hasil keranjang mengembalikan stok SETIAP item.
-- Fungsi cancel_my_order/admin_update_order lama tetap digunakan, tanpa ditimpa.
-- Perintah pembatalan lama hanya mengembalikan stok saat orders.product_id IS NOT NULL;
-- order dari keranjang sengaja memakai product_id NULL, lalu trigger ini mengembalikan stoknya.
CREATE OR REPLACE FUNCTION public.restock_cart_order_on_cancel()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF OLD.order_status <> 'cancelled' AND NEW.order_status = 'cancelled' AND NEW.product_id IS NULL THEN
    UPDATE public.products p SET stock=p.stock+li.quantity,updated_at=now()
    FROM public.order_line_items li
    WHERE li.order_id=NEW.id AND li.product_id=p.id;
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS restore_cart_order_stock ON public.orders;
CREATE TRIGGER restore_cart_order_stock
AFTER UPDATE OF order_status ON public.orders
FOR EACH ROW WHEN (OLD.order_status IS DISTINCT FROM NEW.order_status AND NEW.order_status='cancelled')
EXECUTE FUNCTION public.restock_cart_order_on_cancel();

