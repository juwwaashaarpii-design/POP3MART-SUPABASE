CREATE TABLE IF NOT EXISTS public.payment_methods (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('qris','bank')),
  provider text NOT NULL DEFAULT '',
  account_name text NOT NULL DEFAULT '',
  account_number text NOT NULL DEFAULT '',
  qris_image_url text NOT NULL DEFAULT '',
  instructions text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.profiles(id),
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL,
  product_image_url text,
  unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 20),
  subtotal numeric(14,2) NOT NULL CHECK (subtotal >= 0),
  shipping_fee numeric(14,2) NOT NULL DEFAULT 0 CHECK (shipping_fee >= 0),
  total_amount numeric(14,2) NOT NULL CHECK (total_amount >= 0),
  shipping_address text NOT NULL,
  payment_method_id bigint REFERENCES public.payment_methods(id) ON DELETE SET NULL,
  payment_method_snapshot jsonb NOT NULL,
  order_status text NOT NULL DEFAULT 'awaiting_payment'
    CHECK (order_status IN ('awaiting_payment','under_review','paid','processing','shipped','completed','cancelled')),
  payment_status text NOT NULL DEFAULT 'unpaid'
    CHECK (payment_status IN ('unpaid','submitted','verified','rejected')),
  payment_proof_path text,
  payment_reference text NOT NULL DEFAULT '',
  admin_note text NOT NULL DEFAULT '',
  tracking_number text NOT NULL DEFAULT '',
  paid_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_user_created_idx ON public.orders(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS orders_status_created_idx ON public.orders(order_status, created_at DESC);

