VALUES ('payment-proofs','payment-proofs',false,5242880,ARRAY['image/png','image/jpeg','image/webp','application/pdf'])
ON CONFLICT (id) DO UPDATE SET public=false, file_size_limit=EXCLUDED.file_size_limit,
 allowed_mime_types=EXCLUDED.allowed_mime_types;
DROP POLICY IF EXISTS "Owner upload own proof" ON storage.objects;
DROP POLICY IF EXISTS "Owner or admin read payment proofs" ON storage.objects;
CREATE POLICY "Owner upload own proof" ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'payment-proofs'
  AND split_part(name,'/',1) = (SELECT auth.uid())::text
  AND EXISTS (
    SELECT 1 FROM public.orders o
    WHERE o.user_id = (SELECT auth.uid())
      AND o.id::text = split_part(name,'/',2)
      AND o.order_status = 'awaiting_payment'
  )
);
CREATE POLICY "Owner or admin read payment proofs" ON storage.objects FOR SELECT TO authenticated
USING (
  bucket_id = 'payment-proofs' AND
  (split_part(name,'/',1) = (SELECT auth.uid())::text OR public.is_admin())
);

-- Checkout: snapshot harga dan metode, decrement stok secara atomik, limit jumlah.
CREATE OR REPLACE FUNCTION public.place_order(
  p_product_id bigint, p_quantity integer, p_payment_method_id bigint, p_shipping_address text
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_product public.products%ROWTYPE;
  v_method public.payment_methods%ROWTYPE;
  v_fee numeric(14,2);
  v_address text;
  v_id uuid;
BEGIN
  IF v_uid IS NULL OR NOT EXISTS (SELECT 1 FROM public.profiles WHERE id=v_uid AND role='buyer') THEN
    RAISE EXCEPTION 'Login sebagai Buyer terlebih dahulu.';
  END IF;
  IF p_quantity IS NULL OR p_quantity < 1 OR p_quantity > 20 THEN
    RAISE EXCEPTION 'Jumlah pembelian harus antara 1 sampai 20.';
  END IF;
  v_address := trim(coalesce(p_shipping_address,''));
  IF char_length(v_address) < 10 OR char_length(v_address) > 1000 THEN
    RAISE EXCEPTION 'Alamat pengiriman harus 10-1000 karakter.';
  END IF;
  SELECT * INTO v_product FROM public.products WHERE id=p_product_id AND is_active FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Produk tidak tersedia.'; END IF;
  IF v_product.stock < p_quantity THEN RAISE EXCEPTION 'Stok tidak mencukupi.'; END IF;
  SELECT * INTO v_method FROM public.payment_methods WHERE id=p_payment_method_id AND is_active;
  IF NOT FOUND THEN RAISE EXCEPTION 'Metode pembayaran tidak tersedia.'; END IF;
  IF (v_method.kind='bank' AND (v_method.account_number='' OR v_method.account_name=''))
     OR (v_method.kind='qris' AND v_method.qris_image_url='') THEN
    RAISE EXCEPTION 'Metode pembayaran belum dikonfigurasi lengkap.';
  END IF;
  SELECT COALESCE(shipping_fee,0) INTO v_fee FROM public.store_settings WHERE id=1;
  v_fee := COALESCE(v_fee,0);
  UPDATE public.products SET stock=stock-p_quantity,updated_at=now() WHERE id=p_product_id;
  INSERT INTO public.orders (
    user_id,product_id,product_name,product_image_url,unit_price,quantity,
    subtotal,shipping_fee,total_amount,shipping_address,payment_method_id,payment_method_snapshot
  ) VALUES (
    v_uid,p_product_id,v_product.name,v_product.image_url,v_product.price,p_quantity,
    v_product.price*p_quantity,v_fee,v_product.price*p_quantity+v_fee,v_address,
    p_payment_method_id,jsonb_build_object(
      'name',v_method.name,'kind',v_method.kind,'provider',v_method.provider,
      'account_name',v_method.account_name,'account_number',v_method.account_number,
      'qris_image_url',v_method.qris_image_url,'instructions',v_method.instructions)
  ) RETURNING id INTO v_id;
  RETURN v_id;
END; $$;

-- Buyer can only attach proof to their own awaiting-payment order.
CREATE OR REPLACE FUNCTION public.submit_payment_proof(
  p_order_id uuid, p_storage_path text, p_reference text DEFAULT ''
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_order public.orders%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Login diperlukan.'; END IF;
  SELECT * INTO v_order FROM public.orders WHERE id=p_order_id FOR UPDATE;
  IF NOT FOUND OR v_order.user_id <> auth.uid() THEN RAISE EXCEPTION 'Pesanan tidak ditemukan.'; END IF;
  IF v_order.order_status <> 'awaiting_payment' THEN RAISE EXCEPTION 'Pesanan ini tidak dapat menerima bukti baru.'; END IF;
  IF p_storage_path IS NULL OR char_length(p_storage_path) > 500 OR
    split_part(p_storage_path,'/',1) <> auth.uid()::text OR
    split_part(p_storage_path,'/',2) <> p_order_id::text OR
    split_part(p_storage_path,'/',3) = '' THEN
    RAISE EXCEPTION 'Lokasi bukti pembayaran tidak valid.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM storage.objects WHERE bucket_id='payment-proofs' AND name=p_storage_path) THEN
    RAISE EXCEPTION 'Bukti pembayaran belum berhasil diunggah.';
  END IF;
  UPDATE public.orders SET payment_proof_path=p_storage_path,
    payment_reference=left(trim(coalesce(p_reference,'')),120),
    payment_status='submitted',order_status='under_review',admin_note='',updated_at=now()
  WHERE id=p_order_id;
END; $$;

-- Admin approval NEVER automatic. Admin needs to verify actual funds with merchant bank/QRIS.
CREATE OR REPLACE FUNCTION public.admin_update_order(
  p_order_id uuid, p_action text, p_note text DEFAULT '', p_tracking_number text DEFAULT ''
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_order public.orders%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN RAISE EXCEPTION 'Hanya Admin yang diizinkan.'; END IF;
  SELECT * INTO v_order FROM public.orders WHERE id=p_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pesanan tidak ditemukan.'; END IF;
  IF p_action='approve' THEN
    IF v_order.order_status <> 'under_review' OR v_order.payment_status <> 'submitted' OR v_order.payment_proof_path IS NULL THEN
      RAISE EXCEPTION 'Pesanan tidak memiliki bukti pembayaran untuk diverifikasi.';
    END IF;
    UPDATE public.orders SET order_status='paid',payment_status='verified',paid_at=now(),
      admin_note=left(trim(coalesce(p_note,'')),500),updated_at=now() WHERE id=p_order_id;
  ELSIF p_action='reject' THEN
    IF v_order.order_status <> 'under_review' OR v_order.payment_status <> 'submitted' THEN
      RAISE EXCEPTION 'Hanya bukti yang menunggu pemeriksaan dapat ditolak.';
    END IF;
    UPDATE public.orders SET order_status='awaiting_payment',payment_status='rejected',payment_proof_path=NULL,
      admin_note=left(trim(coalesce(p_note,'')),500),updated_at=now() WHERE id=p_order_id;
  ELSIF p_action='process' THEN
    IF v_order.order_status <> 'paid' THEN RAISE EXCEPTION 'Pembayaran belum diverifikasi.'; END IF;
    UPDATE public.orders SET order_status='processing',updated_at=now() WHERE id=p_order_id;
  ELSIF p_action='ship' THEN
    IF v_order.order_status <> 'processing' OR length(trim(coalesce(p_tracking_number,''))) < 3 THEN
      RAISE EXCEPTION 'Pesanan harus diproses dan memiliki nomor resi.';
    END IF;
    UPDATE public.orders SET order_status='shipped',tracking_number=left(trim(p_tracking_number),120),updated_at=now() WHERE id=p_order_id;
  ELSIF p_action='complete' THEN
    IF v_order.order_status <> 'shipped' THEN RAISE EXCEPTION 'Pesanan belum dikirim.'; END IF;
    UPDATE public.orders SET order_status='completed',updated_at=now() WHERE id=p_order_id;
  ELSIF p_action='cancel' THEN
    IF v_order.order_status NOT IN ('awaiting_payment','under_review','paid','processing') THEN
      RAISE EXCEPTION 'Pesanan tidak dapat dibatalkan pada status ini.';
    END IF;
    IF v_order.product_id IS NOT NULL THEN
      UPDATE public.products SET stock=stock+v_order.quantity,updated_at=now() WHERE id=v_order.product_id;
    END IF;
    UPDATE public.orders SET order_status='cancelled',admin_note=left(trim(coalesce(p_note,'')),500),updated_at=now()
    WHERE id=p_order_id;
  ELSE
    RAISE EXCEPTION 'Aksi tidak dikenal.';
  END IF;
END; $$;

CREATE OR REPLACE FUNCTION public.cancel_my_order(p_order_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_order public.orders%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Login diperlukan.'; END IF;
  SELECT * INTO v_order FROM public.orders WHERE id=p_order_id FOR UPDATE;
  IF NOT FOUND OR v_order.user_id <> auth.uid() THEN RAISE EXCEPTION 'Pesanan tidak ditemukan.'; END IF;
  IF v_order.order_status <> 'awaiting_payment' OR v_order.payment_status NOT IN ('unpaid','rejected') THEN
    RAISE EXCEPTION 'Pesanan yang sudah diajukan pembayarannya tidak dapat dibatalkan sendiri.';
  END IF;
  IF v_order.product_id IS NOT NULL THEN
    UPDATE public.products SET stock=stock+v_order.quantity,updated_at=now() WHERE id=v_order.product_id;
  END IF;
  UPDATE public.orders SET order_status='cancelled',updated_at=now() WHERE id=p_order_id;
END; $$;

